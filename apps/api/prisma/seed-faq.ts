async function main() {
	console.log('🌱 Starting FAQ seed...\n')

	try {
		// Проверяем подключение к базе
		await prisma.$connect()
		console.log('✅ Connected to database\n')

		// Удаляем старые FAQ (опционально)
		const deleteCount = await prisma.fAQEntry.deleteMany()
		console.log(`🗑️  Deleted ${deleteCount.count} old FAQ entries\n`)

		// Создаём новые FAQ
		for (const faq of FAQ_DATA) {
			const created = await prisma.fAQEntry.create({
				data: faq,
			})
			console.log(
				`✅ FAQ Entry created: ${created.question} (${created.category})`,
			)
		}

		console.log(`\n🎉 Successfully seeded ${FAQ_DATA.length} FAQ entries!`)
	} catch (error) {
		console.error('❌ Error seeding FAQ:', error)
		throw error
	} finally {
		await prisma.$disconnect()
		await pool.end()
	}
}

main()
	.catch((e) => {
		console.error(e)
		process.exit(1)
	})
